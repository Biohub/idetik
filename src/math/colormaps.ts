/** The names of the built-in colormaps. */
export type ColormapName = keyof typeof COLORMAP_HEX;

export const COLORMAP_NAMES = Object.keys(COLORMAP_HEX) as ColormapName[];

/**
 * Returns a 256-entry RGBA lookup table for a built-in colormap.
 *
 * @param name - The colormap name.
 */
export function colormapLut(name: ColormapName): Uint8Array {
  const hex = COLORMAP_HEX[name];
  const lut = new Uint8Array(256 * 4);
  for (let i = 0; i < 256; i++) {
    for (let c = 0; c < 3; c++) {
      const offset = 2 * (3 * i + c);
      lut[4 * i + c] = parseInt(hex.slice(offset, offset + 2), 16);
    }
    lut[4 * i + 3] = 255;
  }
  return lut;
}
